const randomIndex = (maxExclusive: number, rng: () => number): number => {
	return Math.floor(rng() * maxExclusive);
};

export const generateName = (rng: () => number = Math.random): string => {
	const max = Math.min(nameA.length, nameB.length);
	if (max <= 0) return "Player";
	if (max === 1) return `${nameA[0]}${nameB[0]}`;
	const firstIndex = randomIndex(max, rng);
	let secondIndex = randomIndex(max - 1, rng);
	if (secondIndex >= firstIndex) secondIndex += 1;
	return `${nameA[firstIndex]}${nameB[secondIndex]}`;
};

